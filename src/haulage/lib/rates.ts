export function slab(distance: number) {
  if (!Number.isFinite(distance) || distance <= 0) return null;
  const index = Math.ceil(distance / 50) - 1;
  return { from: index * 50 + 1, to: (index + 1) * 50, index };
}
export function ratesAt(distance: number): readonly number[] | null {
  const range = slab(distance);
  if (!range) return null;
  if (range.index < 70) return RATE_TABLE[range.index] ?? null;
  const last = RATE_TABLE[69];
  const previous = RATE_TABLE[68];
  if (!last || !previous) return null;
  return last.map((rate, i) => rate + (range.index - 69) * (rate - (previous[i] ?? 0)));
}
